/**
 * @file task3.h
 * @brief Задание №3: структура SafeArray, безопасный доступ к элементам и изменение размера.
 * @details Задание выполнено в две части: пункты 1–5 — версия v0.3,
 * пункт 6 (изменение размера массива) — версия v0.4. Условие задания:
 * > Безопасный массив.
 * > - Объявите структуру `struct SafeArray { int* data; int size; };`.
 * > - Напишите функцию `SafeArray createArray(int size)`, которая выделяет
 * >   память и возвращает структуру по значению.
 * > - Напишите функцию доступа к элементам `int& getElement(SafeArray& arr, int index)`.
 * >   Внутри функции проверьте, не вышел ли index за границы arr.size. Если
 * >   вышел — выведите ошибку и верните ссылку на статическую локальную
 * >   переменную-заглушку (чтобы программа не упала, но изменение не сломало
 * >   основной массив). Если индекс корректный — верните ссылку на `arr.data[index]`.
 * > - Покажите, что вашу функцию можно использовать слева от знака равенства:
 * >   `getElement(myArr, 2) = 999;`.
 * > - Напишите функцию `void printSafe(const SafeArray& arr)`, которая выводит
 * >   массив, используя const (так как печать не требует изменения данных).
 * > - Напишите функцию `reSizeArray(int N, int M)`, которая изменяет размер массива
 * >   с N элементов на M элементов. Если элементов в массиве стало меньше, на экран
 * >   должны быть выведены удалённые элементы. Если элементов стало больше, новые
 * >   элементы должны стать равны 0 по умолчанию.
 *
 * Структура SafeArray хранит вместе указатель на динамический массив и его
 * размер, поэтому функции получают одну структуру вместо пары «указатель + размер»
 * и всегда знают границы массива.
 *
 * Подробное описание решения с примером работы — на странице @ref task3.
 * @author Vareshka86
 * @date 2026-10-02
 * @version 0.4
 */

#ifndef TASK3_H
#define TASK3_H

/**
 * @brief «Безопасный массив»: динамический массив вместе с его размером.
 * @details Память под элементы выделяет createArray(), освобождает freeSafeArray().
 * @warning При копировании структуры копируются только указатель и размер, а не
 * сами элементы: две копии смотрят на одну и ту же память. Освобождать её
 * нужно ровно один раз.
 */
struct SafeArray
{
    int* data; ///< Указатель на первый элемент динамического массива (nullptr — массива нет)
    int size;  ///< Количество элементов массива
};

/// Наименьший размер массива в Задании №3: нужен элемент с индексом 2,
/// чтобы показать запись `getElement(myArr, 2) = 999`.
constexpr int TASK3_MIN_SIZE = 3;

/// Наибольший размер массива в Задании №3: при нём строка массива помещается
/// в окне консоли шириной 120 символов.
constexpr int TASK3_MAX_SIZE = 15;

/**
 * @brief Создаёт безопасный массив из size элементов, равных 0.
 * @details Выделяет память `new int[size]{}` и возвращает структуру **по значению**:
 * вызывающая сторона получает копию структуры, то есть копию указателя и размера.
 * Сами элементы при этом не копируются — они остаются в динамической памяти.
 * @param size Количество элементов.
 * @return Структура с указателем на новый массив и его размером; при `size <= 0` —
 *         пустая структура `{nullptr, 0}`.
 */
SafeArray createArray(int size);

/**
 * @brief Возвращает ссылку на элемент массива с проверкой границ.
 * @details Функция возвращает **ссылку** `int&`, поэтому её вызов можно ставить
 * как справа от знака равенства (прочитать элемент), так и слева
 * (записать элемент): `getElement(myArr, 2) = 999;`.
 *
 * Если индекс выходит за границы [0; arr.size − 1], выводится сообщение об ошибке
 * и возвращается ссылка на **статическую локальную переменную-заглушку**. Она
 * живёт до конца программы, поэтому ссылку на неё возвращать безопасно, а запись
 * в неё не затрагивает основной массив.
 * @param arr   Ссылка на безопасный массив.
 * @param index Индекс элемента.
 * @return Ссылка на `arr.data[index]` или, при неверном индексе, на заглушку.
 * @note Перед каждой выдачей заглушка обнуляется: чтение по неверному индексу
 * всегда даёт 0, даже если раньше по неверному индексу что-то записали.
 */
int& getElement(SafeArray& arr, int index);

/**
 * @brief Выводит массив в две строки: индексы и значения.
 * @details Массив передаётся по **константной ссылке** `const SafeArray&`: структура
 * не копируется, и функция не может изменить её поля (указатель и размер).
 * Элементы читаются через указатель на константу `const int*`, поэтому функция
 * не может изменить и сами числа. Если массива нет (`data == nullptr`), выводится
 * сообщение и к памяти функция не обращается.
 * @param arr Константная ссылка на выводимый массив.
 */
void printSafe(const SafeArray& arr);

/**
 * @brief Изменяет размер массива с N элементов на M элементов.
 * @details В условии функция записана как `reSizeArray(int N, int M)`. Чтобы она
 * знала, какой массив менять, первым параметром передаётся сам массив по ссылке
 * (как в getElement()); N и M сохраняют смысл из условия: N — текущий размер,
 * M — новый.
 *
 * Как работает:
 * - выделяется новый массив `new int[M]{}` — все его элементы равны 0;
 * - в него копируются первые min(N, M) элементов старого массива;
 * - если M < N, на экран выводятся удалённые элементы (с индексами M … N − 1);
 * - если M > N, новые элементы с индексами N … M − 1 остаются равными 0;
 * - старый массив освобождается `delete[]`, в структуру записываются новый
 *   указатель и новый размер.
 * @param arr Ссылка на безопасный массив, размер которого меняется.
 * @param N   Текущий размер массива; должен совпадать с `arr.size`.
 * @param M   Новый размер массива; должен быть больше 0.
 * @warning Если массива нет (`arr.data == nullptr`), N не совпадает с `arr.size`
 * или M <= 0, выводится сообщение об ошибке и массив не меняется.
 * @note Если M == N, массив не меняется.
 */
void reSizeArray(SafeArray& arr, int N, int M);

/**
 * @brief Освобождает память массива и обнуляет структуру.
 * @details Выполняет `delete[] arr.data`, затем `arr.data = nullptr` и `arr.size = 0`,
 * чтобы в структуре не остался «болтающийся» указатель.
 * @param arr Ссылка на безопасный массив.
 * @note Повторный вызов безопасен: `delete[]` для `nullptr` ничего не делает.
 */
void freeSafeArray(SafeArray& arr);

/**
 * @brief Запускает демонстрацию Задания №3.
 * @details Спрашивает размер, создаёт массив createArray(), заполняет его через
 * getElement() (вызов слева от знака равенства), показывает запись
 * `getElement(myArr, 2) = 999` и обращение по неверному индексу, а затем даёт
 * из меню читать и записывать элементы по любому индексу и менять размер
 * массива reSizeArray(). На выходе освобождает память.
 * @exception std::runtime_error Если поток ввода закончился. Перед тем как
 *            передать исключение дальше, функция освобождает память массива.
 */
void runTask3();

#endif // TASK3_H
