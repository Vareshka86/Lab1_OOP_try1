/**
 * @file task2.h
 * @brief Задание №2: одномерный динамический массив, new/delete и ссылка на указатель.
 * @details Условие задания:
 * > Освоить new/delete, избежать «болтающихся указателей» (dangling pointers)
 * > и утечек памяти. Напишите программу для обработки одномерного
 * > динамического массива.
 * > - Спросите у пользователя размер массива N.
 * > - Выделите память под массив, используя `new int[N]{}`.
 * > - Напишите функцию `void process(int*& arr, int size)`, которая принимает
 * >   ссылку на указатель (чтобы можно было изменить сам указатель, если
 * >   потребуется), находит первый отрицательный элемент и, если такой есть,
 * >   создаёт новый динамический массив, копирует туда все элементы до
 * >   отрицательного, а старую память корректно освобождает (указатель arr
 * >   теперь должен смотреть на новый массив).
 * > - Выведите результат.
 * > - Освободите память и обнулите указатель (`arr = nullptr;`). Попытайтесь
 * >   вывести значение по указателю после обнуления, чтобы продемонстрировать
 * >   безопасное поведение программы.
 *
 * Массив здесь — **динамический**: его размер N становится известен только во
 * время работы программы, поэтому память выделяется оператором `new[]` и
 * освобождается оператором `delete[]`. Указатель на массив передаётся в
 * process() по ссылке (`int*&`), чтобы функция могла заменить сам указатель
 * вызывающей стороны на адрес нового массива.
 *
 * Подробное описание решения с примером работы — на странице @ref task2.
 * @author Vareshka86
 * @date 2026-10-02
 * @version 0.2
 */

#ifndef TASK2_H
#define TASK2_H

/// Наибольший размер массива в Задании №2: при нём строка массива помещается
/// в окне консоли шириной 120 символов.
constexpr int TASK2_MAX_SIZE = 15;

/**
 * @brief Ищет первый отрицательный элемент массива.
 * @param arr  Указатель на первый элемент массива (только чтение, может быть nullptr).
 * @param size Количество элементов в массиве.
 * @return Индекс первого отрицательного элемента или -1, если отрицательных
 *         элементов нет (а также если `arr == nullptr` или `size <= 0`).
 */
int findFirstNegative(const int* arr, int size);

/**
 * @brief Оставляет в массиве только элементы до первого отрицательного.
 * @details Указатель передаётся как **ссылка на указатель** `int*&`. Поэтому
 * функция меняет не свою копию, а сам указатель вызывающей стороны.
 *
 * Если первый отрицательный элемент стоит на позиции k:
 * - выделяется новый массив `new int[k]{}`;
 * - в него копируются элементы `arr[0]` … `arr[k - 1]`;
 * - старый массив освобождается оператором `delete[]`;
 * - указатель `arr` получает адрес нового массива.
 *
 * Если отрицательных элементов нет, массив и указатель не меняются.
 * @param arr  Ссылка на указатель на динамический массив, выделенный через `new[]`.
 * @param size Количество элементов в массиве.
 * @note По условию размер передаётся по значению, поэтому новый размер функция
 * вернуть не может: вызывающая сторона узнаёт его заранее через findFirstNegative().
 * @note Если отрицательный уже первый элемент (k = 0), новый массив пустой:
 * `new int[0]` в C++ разрешён, но обращаться к его элементам нельзя.
 * @warning `arr` должен указывать на массив, выделенный через `new[]`: для
 * другой памяти вызов `delete[]` — неопределённое поведение.
 */
void process(int*& arr, int size);

/**
 * @brief Выводит динамический массив в две строки: индексы и значения.
 * @details Перед обращением к элементам функция проверяет указатель: если
 * `arr == nullptr`, она сообщает об этом и к памяти не обращается, поэтому
 * программа не падает. Пустой массив (`size == 0`) тоже выводится сообщением.
 * @param arr  Указатель на первый элемент массива (только чтение — `const int*`).
 * @param size Количество элементов в массиве.
 */
void printDynamicArray(const int* arr, int size);

/**
 * @brief Освобождает динамический массив и обнуляет указатель.
 * @details Выполняет `delete[] arr;` и `arr = nullptr;`. Указатель передаётся по
 * ссылке, поэтому обнуляется указатель вызывающей стороны и он не остаётся
 * «болтающимся» — со старым адресом уже освобождённой памяти.
 * @param arr Ссылка на указатель на динамический массив.
 * @note Повторный вызов безопасен: `delete[]` для `nullptr` ничего не делает.
 */
void freeArray(int*& arr);

/**
 * @brief Запускает демонстрацию Задания №2 по шагам условия.
 * @details Спрашивает размер N, выделяет память `new int[N]{}`, заполняет массив
 * случайными числами или с клавиатуры, вызывает process(), выводит результат,
 * освобождает память, обнуляет указатель и показывает безопасный вывод по
 * обнулённому указателю.
 * @exception std::runtime_error Если поток ввода закончился. Перед тем как
 *            передать исключение дальше, функция освобождает память массива.
 */
void runTask2();

#endif // TASK2_H
