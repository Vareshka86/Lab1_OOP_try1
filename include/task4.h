/**
 * @file task4.h
 * @brief Задание №4: учёт оценок студентов — двумерный динамический массив и параметры по умолчанию.
 * @details Условие задания:
 * > Разработать систему для учёта оценок студентов.
 * > - Напишите функцию выделения памяти под двумерный массив:
 * >   `int** allocateMatrix(int rows, int cols);`
 * > - Напишите функцию заполнения: `void fillMatrix(int** matrix, int rows, int cols);`
 * > - Напишите функцию красивого вывода с параметрами по умолчанию:
 * >   `void printMatrix(int** matrix, int rows, int cols, bool showBorders = true, std::string title = "Matrix");`
 * >   Если showBorders == true, выводить рамочку из символов * или - вокруг матрицы.
 * >   Вызовите функцию в main три раза: без доп. параметров, только с заголовком
 * >   и со всеми параметрами.
 * > - Напишите функцию `void freeMatrix(int** matrix, int rows)`, которая корректно
 * >   очищает память (сначала вложенные массивы, потом массив указателей).
 *
 * Оценки хранятся в двумерном динамическом массиве: строка — студент, столбец —
 * номер оценки. Двумерный массив устроен как массив указателей `int*`, каждый из
 * которых указывает на свою строку — отдельный массив `int`. Поэтому сама матрица
 * имеет тип «указатель на указатель» `int**`.
 *
 * Подробное описание решения с примером работы — на странице @ref task4.
 * @author Vareshka86
 * @date 2026-10-03
 * @version 1.0
 */

#ifndef TASK4_H
#define TASK4_H

#include <string>

/// Наибольшее количество студентов (строк матрицы) в Задании №4.
constexpr int TASK4_MAX_ROWS = 10;

/// Наибольшее количество оценок у студента (столбцов матрицы) в Задании №4:
/// при нём матрица в рамке помещается в окне консоли шириной 80 символов.
constexpr int TASK4_MAX_COLS = 10;

/// Наименьшая оценка.
constexpr int GRADE_MIN = 2;

/// Наибольшая оценка.
constexpr int GRADE_MAX = 5;

/**
 * @brief Выделяет память под двумерный массив rows × cols, все элементы равны 0.
 * @details Память выделяется в два шага:
 * 1. массив из rows указателей: `new int*[rows]{}` — фигурные скобки сразу
 *    записывают во все указатели nullptr;
 * 2. для каждой строки — массив из cols чисел: `matrix[i] = new int[cols]{}`.
 *
 * Если на шаге 2 памяти не хватит (`new` выбросит исключение `std::bad_alloc`),
 * уже выделенные строки освобождаются через freeMatrix(), и исключение
 * передаётся дальше — утечки нет. Это возможно потому, что указатели ещё не
 * выделенных строк равны nullptr, а `delete[] nullptr` ничего не делает.
 * @param rows Количество строк (студентов).
 * @param cols Количество столбцов (оценок у каждого студента).
 * @return Указатель на массив указателей на строки; при `rows <= 0` или
 *         `cols <= 0` — nullptr (память не выделяется).
 * @exception std::bad_alloc Если не хватило памяти.
 * @warning Память нужно освободить вызовом freeMatrix() с тем же rows.
 */
int** allocateMatrix(int rows, int cols);

/**
 * @brief Заполняет матрицу оценками: случайными или с клавиатуры.
 * @details Спрашивает способ заполнения: случайные оценки от GRADE_MIN до
 * GRADE_MAX или ввод каждой оценки вручную (принимаются только целые числа
 * от GRADE_MIN до GRADE_MAX). Элемент записывается обычной записью
 * `matrix[i][j]`: `matrix[i]` — указатель на строку i, `[j]` — элемент этой строки.
 * @param matrix Матрица, выделенная allocateMatrix(); при nullptr выводится
 *               сообщение и к памяти функция не обращается.
 * @param rows   Количество строк.
 * @param cols   Количество столбцов.
 * @exception std::runtime_error Если поток ввода закончился.
 */
void fillMatrix(int** matrix, int rows, int cols);

/**
 * @brief Выводит матрицу оценок таблицей с заголовком и, при необходимости, рамкой.
 * @details Значения по умолчанию у двух последних параметров указаны только здесь,
 * в объявлении функции; в определении (task4.cpp) их не повторяют. Поэтому
 * функцию можно вызывать по-разному:
 * - `printMatrix(m, r, c);` — рамка есть, заголовок «Matrix»;
 * - `printMatrix(m, r, c, true, "Оценки");` — свой заголовок; showBorders
 *   приходится указать, потому что пропустить параметр в середине списка нельзя;
 * - `printMatrix(m, r, c, false, "Оценки");` — все параметры заданы явно.
 *
 * Рамка рисуется символами `*`, заголовок отделяется от таблицы линией из `-`.
 * Ширина рамки подстраивается под ширину таблицы и длину заголовка.
 * @param matrix      Выводимая матрица; при nullptr выводится сообщение,
 *                    к памяти функция не обращается.
 * @param rows        Количество строк (студентов).
 * @param cols        Количество столбцов (оценок).
 * @param showBorders true — вывести рамку вокруг матрицы (по умолчанию),
 *                    false — без рамки.
 * @param title       Заголовок над таблицей (по умолчанию "Matrix").
 */
void printMatrix(int** matrix, int rows, int cols, bool showBorders = true,
                 std::string title = "Matrix");

/**
 * @brief Освобождает память двумерного массива.
 * @details Порядок важен: сначала `delete[] matrix[i]` для каждой строки,
 * затем `delete[] matrix` для массива указателей. Если сначала удалить массив
 * указателей, адреса строк будут потеряны, и строки освободить уже не получится
 * (утечка памяти), а чтение `matrix[i]` из освобождённой памяти — ошибка.
 * @param matrix Матрица, выделенная allocateMatrix(); для nullptr функция ничего не делает.
 * @param rows   Количество строк — то же, что при выделении.
 * @note Указатель передаётся по значению, поэтому функция не может обнулить
 * указатель вызывающей стороны: после вызова его обнуляют сами
 * (`grades = nullptr;`), чтобы он не остался «болтающимся».
 */
void freeMatrix(int** matrix, int rows);

/**
 * @brief Запускает демонстрацию Задания №4 по шагам условия.
 * @details Спрашивает количество студентов и оценок, выделяет память
 * allocateMatrix(), заполняет её fillMatrix(), вызывает printMatrix() три раза
 * (без дополнительных параметров, только с заголовком, со всеми параметрами),
 * освобождает память freeMatrix() и обнуляет указатель.
 * @exception std::runtime_error Если поток ввода закончился. Перед тем как
 *            передать исключение дальше, функция освобождает память матрицы.
 */
void runTask4();

#endif // TASK4_H
