/**
 * @file random_number.h
 * @brief Случайные целые числа: общий модуль для всех заданий.
 * @details Генератор случайных чисел создаётся один раз и используется всеми
 * заданиями лабораторной работы, которые заполняют массивы случайными числами
 * (Задание №1 и Задание №2). Поэтому он вынесен в отдельный модуль, а не
 * повторяется в каждом задании.
 * @author Vareshka86
 * @date 2026-10-02
 * @version 0.2
 */

#ifndef RANDOM_NUMBER_H
#define RANDOM_NUMBER_H

/// Нижняя граница случайных чисел при заполнении массивов.
constexpr int RANDOM_MIN = -50;

/// Верхняя граница случайных чисел при заполнении массивов.
constexpr int RANDOM_MAX = 50;

/**
 * @brief Возвращает случайное целое число из отрезка [minValue; maxValue].
 * @details Числа распределены равномерно: каждое значение из отрезка выпадает
 * с одинаковой вероятностью. Генератор создаётся один раз при первом вызове
 * и при каждом запуске программы получает новое случайное начальное значение,
 * поэтому от запуска к запуску числа разные.
 * @param minValue Наименьшее возможное значение.
 * @param maxValue Наибольшее возможное значение.
 * @return Случайное число, лежащее в отрезке [minValue; maxValue].
 * @warning Должно выполняться условие minValue <= maxValue.
 */
int randomInt(int minValue, int maxValue);

#endif // RANDOM_NUMBER_H
